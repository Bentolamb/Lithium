// Lithium-only blocks in the GUI: run, placeholder form on save, and restore on load.
const http=require('http'),fs=require('fs'),path=require('path');
const { chromium } = require(process.env.PW || '/opt/npm-tools/node_modules/playwright-core');
const root=process.env.GUI_BUILD||'/home/claude/tw/scratch-gui/build';
const types={'.html':'text/html','.js':'text/javascript','.css':'text/css','.svg':'image/svg+xml','.png':'image/png','.wasm':'application/wasm','.json':'application/json'};
const srv=http.createServer((q,r)=>{let f=path.join(root,decodeURIComponent(q.url.split('?')[0]));if(q.url==='/'||q.url.startsWith('/?'))f=path.join(root,'editor.html');if(!fs.existsSync(f)||fs.statSync(f).isDirectory()){r.writeHead(404);r.end();return}r.writeHead(200,{'content-type':types[path.extname(f)]||'application/octet-stream'});fs.createReadStream(f).pipe(r)});
let fails=0;const check=(n,ok,x)=>{console.log((ok?'PASS ':'FAIL ')+n+(ok?'':'  '+(x||'')));if(!ok)fails++};
srv.listen(0,async()=>{
 const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium',args:['--use-angle=swiftshader','--use-gl=angle','--enable-unsafe-swiftshader','--no-sandbox']});
 const p=await b.newPage({viewport:{width:1400,height:800}});
 p.on('pageerror',e=>console.log('pageerror',String(e).slice(0,300)));
 p.on('console',m=>{if(m.type()==='error')console.log('console.error',m.text().slice(0,200))});
 await p.goto('http://localhost:'+srv.address().port+'/editor.html');
 await p.waitForFunction(()=>window.vm&&window.vm.renderer&&window.vm.initialized,null,{timeout:60000});
 await new Promise(r=>setTimeout(r,2000));
 const sb3=fs.readFileSync(path.join(__dirname,'ext_test.sb3')).toString('base64');
 await p.evaluate(async b64=>{const bin=Uint8Array.from(atob(b64),c=>c.charCodeAt(0));await window.vm.loadProject(bin.buffer);},sb3);
 await new Promise(r=>setTimeout(r,1500));
 check('extensions registered', await p.evaluate(()=>['lithiumlab','packin','outlist'].every(e=>window.vm.extensionManager.isExtensionLoaded(e))));
 await p.evaluate(()=>window.vm.greenFlag());
 const ok=await p.waitForFunction(()=>window.vm.lithium&&window.vm.lithium.active&&String(window.vm.lithium.lith.state().targets[0].variables.ext_done)==='1',null,{timeout:30000}).then(()=>true).catch(()=>false);
 check('script with extension blocks ran', ok, await p.evaluate(()=>String(window.vm.lithium.error)));
 const st=await p.evaluate(()=>{const s=window.vm.lithium.lith.state().targets[0];return {v:s.variables,l:s.lists}});
 console.log(JSON.stringify(st));
 check('packin round trip', st.v.xx==='hello hello hello hello', st.v.xx);
 check('outlist saved, exists, reloaded list', String(st.v.xr)==='true' && JSON.stringify(st.l.XL)==='["a","b","c"]', JSON.stringify(st.l));
 check('is Lithium? true', String(st.v.xe)==='true');
 check('is TurboWarp? false', String(st.v.xl)==='false');
 await p.evaluate(()=>window.vm.stopAll());
 await new Promise(r=>setTimeout(r,500));
 const json=await p.evaluate(()=>window.vm.toJSON());
 const proj=JSON.parse(json);
 const ops=Object.values(proj.targets[0].blocks).filter(x=>!Array.isArray(x)).map(x=>x.opcode+':'+(x.mutation&&x.mutation.proccode||''));
 check('save writes placeholders', ops.some(o=>o==='procedures_call:Lithium-only Extension block') && !ops.some(o=>/^(outlist|packin|lithiumlab)_/.test(o)), ops.join(','));
 check('extensions removed from saved list', !proj.extensions.some(e=>['outlist','packin','lithiumlab'].includes(e)), JSON.stringify(proj.extensions));
 await p.evaluate(async j=>{await window.vm.loadProject(j);},json);
 await new Promise(r=>setTimeout(r,1500));
 const ops2=await p.evaluate(()=>Object.values(window.vm.runtime.getTargetForStage().blocks._blocks).map(x=>x.opcode));
 check('reopening restores the real blocks', ops2.includes('outlist_saveList')&&ops2.includes('packin_compress')&&ops2.includes('lithiumlab_isLithium'), ops2.join(','));
 await p.evaluate(()=>window.vm.greenFlag());
 const ok2=await p.waitForFunction(()=>window.vm.lithium.active&&String(window.vm.lithium.lith.state().targets[0].variables.ext_done)==='1',null,{timeout:30000}).then(()=>true).catch(()=>false);
 check('restored project runs again', ok2);
 await b.close();srv.close();
 console.log(fails?fails+' FAILED':'all passed');process.exit(fails?1:0);
});
