#!/usr/bin/env python3
"""Generates runtime/src/unicode_case_data.inc: per-character full lower/upper
case mappings (Unicode SpecialCasing included), matching what JavaScript's
String.prototype.toLowerCase/toUpperCase apply to a single code point.
Context-dependent rules (final sigma) are handled in text.cpp.
Run: python3 tools/gen_unicode_case.py > runtime/src/unicode_case_data.inc
"""
import sys
import unicodedata

def table(fn):
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        m = fn(c)
        if m != c:
            cps = [ord(x) for x in m]
            assert len(cps) <= 3
            rows.append((cp, cps + [0] * (3 - len(cps))))
    return rows

def emit(name, rows):
    print(f"static const CaseEntry {name}[] = {{")
    for cp, m in rows:
        print(f"    {{0x{cp:X}, {{0x{m[0]:X}, 0x{m[1]:X}, 0x{m[2]:X}}}}},")
    print("};")

print(f"// Generated by tools/gen_unicode_case.py from Unicode {unicodedata.unidata_version}. Do not edit.")
emit("kLowerTable", table(str.lower))
emit("kUpperTable", table(str.upper))
